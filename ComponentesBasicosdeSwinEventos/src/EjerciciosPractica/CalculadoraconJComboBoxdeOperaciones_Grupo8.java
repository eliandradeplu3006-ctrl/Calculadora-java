    private void validarNumeros(java.awt.event.KeyEvent evt, String textoActual) {
        char c = evt.getKeyChar();
        if (!Character.isDigit(c) && c != '.') {
            evt.consume();
        }
        if (c == '.' && textoActual.contains(".")) {
            evt.consume();
        }
    }
    
