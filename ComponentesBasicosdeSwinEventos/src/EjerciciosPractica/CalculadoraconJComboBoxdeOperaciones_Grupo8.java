    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
    try {
            
            if (txtNumero1.getText().trim().isEmpty() || txtNumero2.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, 
                    "Debe ingresar ambos números para realizar la operación", 
                    "Datos Faltantes", 
                    JOptionPane.WARNING_MESSAGE); 
                return;
            }

            double n1 = Double.parseDouble(txtNumero1.getText());
            double n2 = Double.parseDouble(txtNumero2.getText());
            String op = cbxOperaciones.getSelectedItem().toString();
            double res = 0;

           
            switch (op) {
                case "Suma" -> res = n1 + n2;
                case "Resta" -> res = n1 - n2;
                case "Multiplicación" -> res = n1 * n2;
                case "División" -> {
                 
                    if (n2 == 0) {
                        JOptionPane.showMessageDialog(this, 
                            "Error: No es posible dividir para cero", 
                            "Error Matemático", 
                            JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                    res = n1 / n2;
                }
            }

            txtResultado.setText(String.format("%.2f", res));

        } catch (NumberFormatException e) {
            
            JOptionPane.showMessageDialog(this, 
                "Solo se permiten valores numéricos válidos", 
                "Error de Formato", 
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

